/*
 * mod-sanctuary-gm - the Timekeeper, the game masters' class
 *
 * A game master's own character wears a class nobody else can have, so it reads as staff on
 * sight: "Level 80 Human Timekeeper". It lives in class slot 10, the one hole in 3.3.5a's
 * list between Warlock and Druid, so Death Knight is untouched and stays free to open up.
 *
 * Nobody can choose it. The creation screen is patched not to offer it and this module
 * refuses it anyway, because the screen is only the client's opinion. The only way in is
 *
 *     .gmclass set <name>               make a logged-in character a Timekeeper
 *     .gmclass revert <name> <class>    and back again, e.g. `.gmclass revert Aldric paladin`
 *
 * and the character has to belong to an account with game master security - the same
 * SanctuaryGM.RequiredSecurity the panel answers to.
 *
 *
 * ITS TWO SPELLS, and the only ones it has: 81014 "True Visage", a dragon at half scale for
 * a fight indoors, and 81015 "Winged Visage", a drake with an epic mount's ground and flight
 * speed for getting somewhere. Both are infinite self-auras, so the buff is the toggle, and
 * taking one puts the other away. The speed rides on the spell rather than being set here,
 * because a hand-set speed is recalculated away by the next aura or mount.
 *
 *
 * WHAT BECOMING A TIMEKEEPER DOES. The old class goes: its talents (every spec), its glyphs,
 * and every skill the new class may not hold - which takes every spell that skill taught
 * with it. What every class shares stays: professions, riding, languages, mounts and pets.
 * The Timekeeper then learns every language (fluent), every profession (Grand Master, 450)
 * and every weapon and armour proficiency (weapon skills at the cap for its level), so a
 * game master can understand anyone and dress for whatever an event needs. It has no class
 * spells of its own; game masters have commands. The same kit is topped up at every
 * Timekeeper's login, and `.gmclass set` on a Timekeeper re-teaches it on the spot.
 *
 * The character is then logged out. A class is not something the client expects to change
 * under it, and a fresh login is the one path that rebuilds everything - stats, power type,
 * spellbook, action bars - from the new class rather than patching the old one in place.
 *
 *
 * WHAT HAS TO EXIST FIRST, and all of it is generated by tools/assets/make-patch.py from one
 * number (GM_CLASS_ID) so the halves cannot drift:
 *
 *   the client   ChrClasses row 10, or the class has no name on anyone's screen
 *   the server   chrclasses_dbc, skillraceclassinfo_dbc, playercreateinfo and
 *                player_class_stats rows (data/sql/db-world/..._sanctuary_gm_class.sql).
 *                Without creation info a Timekeeper cannot even be loaded, and without
 *                stats for every level the worldserver will not start.
 */

