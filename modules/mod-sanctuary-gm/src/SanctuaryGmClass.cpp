    /*
     * The class's two forms.
     *
     * Spells rather than panel buttons, because a form is something you flick on and off
     * from an action bar mid-event. Each is an infinite self-aura, so the buff itself is the
     * toggle: right-click it, or cast it again, and the form comes off.
     *
     * What the aura cannot do is the morph. A DBC transform aura takes a creature ENTRY and
     * these are DISPLAYS, so the module does the morph and the scale when the aura goes on
     * and comes off. The speed, on the other hand, is on the spell row and not here - see
     * the SQL for why a hand-set speed does not last.
     */
    /*
     * The puff of smoke a druid changes shape inside. Without it a form is one model
     * silently replacing another, which reads as a glitch rather than a change.
     *
     * **This is a SpellVisualKit id, not a SpellVisual id, and the two are different
     * tables.** SMSG_PLAY_SPELL_VISUAL carries a kit index; a spell row's SpellVisualID
     * points at a SpellVisual, which in turn names up to six kits for the stages of a cast.
     * Cat Form casts with SpellVisual 4228, whose impact kit - the puff that lands on the
     * caster - is 3610, and that is what this is. Sending 4228 here draws nothing at all,
     * silently, which is exactly what it did the first time.
     *
     * Played by the server rather than set on the spell row, because a spell's own visual
     * plays when it is CAST and nothing plays when a buff is cancelled - and the change back
     * wants covering just as much as the change out.
     *
     * The kit is Sanctuary's own, added by tools/assets/make-patch.py: it is Cat Form's
     * impact kit with the puff enlarged, because at its own size - built for a person - the
     * smoke was lost against a dragon. The size is client data and cannot be sent from
     * here, since the packet carries a kit id and nothing else. Change SMOKE_SCALE there.
     */
    constexpr uint32 SHAPESHIFT_SMOKE = 15600;

    struct Form
    {
        uint32 spell;
        uint32 display;
        float scale;
        bool flies;
        uint32 visual;
    };

    constexpr Form Forms[] =
    {
        // A bronze dragon at its own size - display 19373, which the Steward of Time wears,
        // and whose model already carries a half scale of its own.
        { 81014, 19373, 1.0f, false, SHAPESHIFT_SMOKE },

        // A drake, at its own size, for getting somewhere.
        { 81015, 25852, 1.0f, true,  SHAPESHIFT_SMOKE },
    };

    constexpr Form const* FindForm(uint32 spell)
    {
        for (Form const& form : Forms)
            if (form.spell == spell)
                return &form;

        return nullptr;
    }

